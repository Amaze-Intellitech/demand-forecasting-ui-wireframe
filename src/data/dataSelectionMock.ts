// Helper to compute date range from preset
export const computePeriodDates = (preset: '1' | '3' | '5' | '10' | 'custom'): DataPeriodConfig => {
  const today = new Date('2026-09-22');
  const endDateStr = today.toISOString().split('T')[0];

  const yearsBack = preset === '1' ? 1 : preset === '3' ? 3 : preset === '5' ? 5 : preset === '10' ? 10 : 3;
  const startDate = new Date(today);
  startDate.setFullYear(today.getFullYear() - yearsBack);
  const startDateStr = startDate.toISOString().split('T')[0];

  return {
    presetYears: preset,
    startDate: startDateStr,
    endDate: endDateStr,
  };
};

